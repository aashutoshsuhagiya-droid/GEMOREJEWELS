// Approximate units per USD. Runtime rates replace these when a provider or persisted snapshot is available.
export const STATIC_USD_RATES = Object.freeze(Object.fromEntries(
  currencyOptions.map(({ code }) => [code, code === "USD" ? 1 : REFERENCE_CROSS_RATES[code] / REFERENCE_CROSS_RATES.USD])
)) as Readonly<Record<CurrencyCode, number>>;

export function isCurrencyCode(value: unknown): value is CurrencyCode {
  return currencyOptions.some(option => option.code === value);
}

function usableRates(value: CurrencyRates | number | undefined): CurrencyRates {
  return value && typeof value === "object" ? value : STATIC_USD_RATES;
}

export function currencyAmount(usdValue: number, currency: CurrencyCode, ratesOrLegacyValue?: CurrencyRates | number): number {
  const rates = usableRates(ratesOrLegacyValue);
  const candidate = Number(rates[currency]);
  const rate = Number.isFinite(candidate) && candidate > 0 ? candidate : STATIC_USD_RATES[currency];
  return Math.round(usdValue * rate);
}

export function formatCurrencyAmount(usdValue: number, currency: CurrencyCode, ratesOrLegacyValue?: CurrencyRates | number): string {
  const option = currencyOptions.find(item => item.code === currency) ?? currencyOptions.find(item => item.code === DEFAULT_CURRENCY)!;
  return new Intl.NumberFormat(option.locale, { style: "currency", currency: option.code }).format(currencyAmount(usdValue, option.code, ratesOrLegacyValue));
}

export function currencySymbol(currency: CurrencyCode): string {
  const option = currencyOptions.find(item => item.code === currency) ?? currencyOptions.find(item => item.code === DEFAULT_CURRENCY)!;
  return new Intl.NumberFormat(option.locale, { style: "currency", currency: option.code })
    .formatToParts(0)
    .find(part => part.type === "currency")?.value ?? option.code;
}
